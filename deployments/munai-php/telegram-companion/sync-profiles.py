def process_client(db: sqlite3.Connection, user_dict: dict, id_value,
                   id_column: str, source: str) -> tuple:
    """Process a single client — generate profile note (no conversation content).
    Returns (safe_name, profile_content, stats)."""

    if source == 'website':
        name = user_dict.get('display_name') or f"Visitor-{user_dict['client_id'][:8]}"
    else:
        name = user_dict.get('first_name') or user_dict.get('username') or f"Client-{id_value}"

    safe_name = sanitize_filename(name)

    # Pull engagement data (messages read only for stats + keyword domains, not synced)
    messages = get_all_messages(db, id_value, id_column)
    profile_summary = user_dict.get('profile_summary', '') or ''
    stats = get_conversation_stats(messages, user_dict['first_seen'], user_dict['last_seen'])
    notes = get_profile_notes(db, id_value, id_column)
    # Privacy: only extract keyword domain coverage, not message text
    highlights = extract_highlights(messages)
    highlights_text = format_highlights_domains_only(highlights)

    # Generate profile note only — no conversation log (privacy boundary)
    profile_content = generate_vault_note(
        user_dict, profile_summary, stats, notes, '',
        highlights_text, safe_name, source=source
    )

    return safe_name, profile_content, stats


def write_client_files(safe_name: str, profile_content: str,
                       stats: dict) -> tuple:
    """Write profile note only (no conversation log — privacy boundary).
    Returns ('created'|'updated')."""
    profile_path = CLIENTS_DIR / f"{safe_name}.md"

    # Profile note — merge manual notes if updating
    if profile_path.exists():
        existing = profile_path.read_text(encoding='utf-8')
        profile_content = update_existing_note(existing, profile_content)
        profile_path.write_text(profile_content, encoding='utf-8')
        action = 'updated'
    else:
        profile_path.write_text(profile_content, encoding='utf-8')
        action = 'created'

    return action


def process_telegram_db(db_path: Path) -> tuple:
    """Process the Telegram companion database. Returns (created, updated, total)."""
    if not db_path.exists():
        print(f"  Telegram database not found at {db_path}, skipping.")
        return 0, 0, 0

    print(f"\n--- Processing Telegram clients ---")
    db = sqlite3.connect(str(db_path))
    db.row_factory = sqlite3.Row
    cursor = db.cursor()

    cursor.execute('SELECT * FROM users ORDER BY last_seen DESC')
    users = cursor.fetchall()

    if not users:
        print("  No Telegram users found.")
        db.close()
        return 0, 0, 0

    created = 0
    updated = 0

    for user in users:
        user_dict = dict(user)
        telegram_id = user_dict['telegram_id']

        safe_name, profile_content, stats = process_client(
            db, user_dict, telegram_id, 'telegram_id', 'telegram'
        )
        action = write_client_files(safe_name, profile_content, stats)

        if action == 'created':
            created += 1
        else:
            updated += 1
        print(f"  {action.capitalize()}: {safe_name}.md ({stats['total_messages']} messages)")

    db.close()
    return created, updated, len(users)


def process_website_db(db_path: Path) -> tuple:
    """Process the website companion database. Returns (created, updated, total)."""
    if not db_path.exists():
        print(f"  Website database not found at {db_path}, skipping.")
