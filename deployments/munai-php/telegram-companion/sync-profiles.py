def sanitize_filename(name: str) -> str:
    """Convert a name to a safe filename."""
    name = re.sub(r'[^\w\s-]', '', name)
    name = re.sub(r'[\s]+', '-', name.strip())
    return name or 'Unknown'


def format_timestamp(ts: int) -> str:
    """Convert Unix timestamp to readable date."""
    return datetime.fromtimestamp(ts, tz=timezone.utc).strftime('%Y-%m-%d')


def format_timestamp_full(ts: int) -> str:
    """Convert Unix timestamp to full datetime."""
    return datetime.fromtimestamp(ts, tz=timezone.utc).strftime('%Y-%m-%d %H:%M')


def get_all_messages(db: sqlite3.Connection, id_value,
                     id_column: str = 'telegram_id') -> list:
    """Get ALL conversation messages for a user, ordered chronologically.
    Returns list of (role, content, timestamp) tuples — untruncated."""
    cursor = db.cursor()
    cursor.execute(f'''
        SELECT role, content, timestamp FROM messages
        WHERE {id_column} = ? ORDER BY timestamp ASC
    ''', (id_value,))
    return cursor.fetchall()


