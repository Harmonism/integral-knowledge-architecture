def generate_vault_note(user: dict, profile_summary: str,
                         stats: dict, notes: list,
                         conversation_excerpt: str,
                         highlights_text: str,
                         safe_name: str,
                         source: str = 'telegram') -> str:
    """Generate a vault-format markdown profile note for a client."""
    if source == 'website':
        name = user.get('display_name') or f"Visitor-{user['client_id'][:8]}"
        client_id = user['client_id']
        id_label = 'client_id'
        id_value = client_id
        source_label = 'Website'
        tags = '[harmonia, companion, client, website]'
    else:
        name = user['first_name'] or user['username'] or f"Client-{user['telegram_id']}"
        id_label = 'telegram_id'
        id_value = user['telegram_id']
        source_label = 'Telegram'
        tags = '[harmonia, companion, client, telegram]'

    first_seen = format_timestamp(user['first_seen'])
    last_seen = format_timestamp(user['last_seen'])

    # Build frontmatter
    frontmatter_lines = [
        '---',
        'domain: guidance',
        f'tags: {tags}',
        f'client_name: "{name}"',
        f'{id_label}: {id_value}',
        f'source: {source}',
    ]
    if source == 'telegram':
        frontmatter_lines.append(f'telegram_username: "{user.get("username") or ""}"')
    frontmatter_lines += [
        f'first_contact: {first_seen}',
        f'last_contact: {last_seen}',
        f'total_messages: {stats["total_messages"]}',
        'maturity: developing',
        '---',
    ]
    frontmatter = '\n'.join(frontmatter_lines)

    # Build the note body
    sections = []

    sections.append(f"# {name}")
    sections.append(f"*Companion client via {source_label}. First contact: {first_seen}. "
                     f"See also: [[The Companion]], [[Wheel of Harmony]].*")
    sections.append("---")

    # Profile Summary (the Companion's accumulated understanding)
    sections.append("## Profile Summary")
    if profile_summary:
        sections.append(profile_summary)
    else:
        sections.append("*The Companion has not yet accumulated enough conversation "
                         "to build a profile. This will populate after sustained dialogue.*")

    # Wheel Position (extracted from profile if present)
    sections.append("## Wheel Position")
    wheel_pos = user.get('wheel_position', '')
    if wheel_pos:
        sections.append(wheel_pos)
    else:
        sections.append("*Not yet assessed. The Companion maps Wheel position through "
                         "ongoing dialogue — it emerges rather than being surveyed.*")

    # Structured Observations
    if notes:
        sections.append("## Observations")
        for category, observation, confidence, updated_at in notes:
            date = format_timestamp(updated_at)
            sections.append(f"**{category}** ({confidence}, {date}): {observation}")

    # Harmonism Highlights
    sections.append("## Harmonism Highlights")
    sections.append(highlights_text)

    # Conversation Statistics
    sections.append("## Engagement")
    sections.append(
        f"Total exchanges: {stats['total_messages']} "
        f"({stats['user_messages']} from client, {stats['companion_messages']} from Companion). "
        f"Active from {stats['first_message']} to {stats['last_message']}."
    )

    # Privacy boundary — no conversation content in vault
    sections.append("## Privacy")
    sections.append("Conversation content remains on the server database only. "
                    "This profile contains the Companion's learned understanding "
                    "(profile summary, Wheel position, observations) but not message text.")

    # Clinical Notes (manual section for Tahir)
    sections.append("## Notes")
    sections.append("%%Add your own observations, guidance notes, or follow-up items here.%%")
    sections.append("")

    # Footer
    sections.append("---")
    sections.append(f"*Auto-generated by Companion Profile Sync. "
                     f"Last synced: {datetime.now().strftime('%Y-%m-%d %H:%M')}.*")

    return frontmatter + "\n\n" + "\n\n".join(sections) + "\n"


def update_existing_note(existing_content: str, new_content: str) -> str:
    """
    Merge new auto-generated content with manually added notes.
    Preserves anything in the '## Notes' section that was added by hand.
    """
    # Extract manual notes from existing file
    manual_notes = ""
    notes_match = re.search(
        r'## Notes\n\n(.*?)(?=\n---\n\*Auto-generated|\Z)',
        existing_content, re.DOTALL
    )
    if notes_match:
        manual_text = notes_match.group(1).strip()
        # Only preserve if it's not just the placeholder comment
        if manual_text and manual_text != "%%Add your own observations, guidance notes, or follow-up items here.%%":
            manual_notes = manual_text

    # If manual notes exist, inject them into the new content
    if manual_notes:
        new_content = new_content.replace(
            "%%Add your own observations, guidance notes, or follow-up items here.%%",
            manual_notes
        )

    return new_content


