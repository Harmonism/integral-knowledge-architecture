def generate_conversation_log(name: str, messages: list, source: str = 'telegram') -> str:
    """Generate a complete, untruncated conversation log as a vault note."""
    source_label = 'Telegram' if source == 'telegram' else 'Website'

    frontmatter = '\n'.join([
        '---',
        'domain: guidance',
        'audience: developer',
        f'tags: [harmonia, companion, conversation-log, {source}]',
        f'client_name: "{name}"',
        f'source: {source}',
        'maturity: developing',
        '---',
    ])

    lines = []
    lines.append(f"# {name} — Conversation Log")
    lines.append(f"*Complete conversation history via {source_label} Companion. "
                 f"See also: [[{name}]].*")
    lines.append("---")

    if not messages:
        lines.append('*No conversations recorded.*')
    else:
        first_ts = format_timestamp(messages[0][2])
        last_ts = format_timestamp(messages[-1][2])
        lines.append(f"**{len(messages)} messages** from {first_ts} to {last_ts}.")
        lines.append("")

        current_date = None
        for role, content, ts in messages:
            msg_date = format_timestamp(ts)
            # Insert date separator when day changes
            if msg_date != current_date:
                current_date = msg_date
                lines.append(f"### {current_date}")
                lines.append("")

            time_str = format_timestamp_full(ts)
            speaker = "**Client**" if role == "user" else "**Companion**"
            lines.append(f"{speaker} ({time_str}):")
            lines.append(content)
            lines.append("")

    lines.append("---")
    lines.append(f"*Auto-generated by Companion Profile Sync. "
                 f"Last synced: {datetime.now().strftime('%Y-%m-%d %H:%M')}.*")

    return frontmatter + "\n\n" + "\n".join(lines) + "\n"


