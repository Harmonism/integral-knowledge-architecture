def get_conversation_stats(messages: list, first_seen: int, last_seen: int) -> dict:
    """Compute conversation statistics from the full message list."""
    user_msgs = sum(1 for r, _, _ in messages if r == 'user')
    companion_msgs = sum(1 for r, _, _ in messages if r == 'assistant')

    if messages:
        first_msg = messages[0][2]
        last_msg = messages[-1][2]
    else:
        first_msg = first_seen
        last_msg = last_seen

    return {
        'user_messages': user_msgs,
        'companion_messages': companion_msgs,
        'total_messages': len(messages),
        'first_message': format_timestamp(first_msg) if first_msg else 'N/A',
        'last_message': format_timestamp(last_msg) if last_msg else 'N/A',
    }


def get_profile_notes(db: sqlite3.Connection, id_value,
                       id_column: str = 'telegram_id') -> list:
    """Get structured profile notes."""
    cursor = db.cursor()
    cursor.execute(f'''
        SELECT category, observation, confidence, updated_at
        FROM profile_notes WHERE {id_column} = ? ORDER BY category
    ''', (id_value,))
    return cursor.fetchall()


