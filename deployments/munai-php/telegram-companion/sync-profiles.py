    cursor.execute('SELECT * FROM clients ORDER BY last_seen DESC')
    clients = cursor.fetchall()

    if not clients:
        print("  No website clients found.")
        db.close()
        return 0, 0, 0

    created = 0
    updated = 0

    for client in clients:
        client_dict = dict(client)
        client_id = client_dict['client_id']

        # Map website schema to the common interface
        user_for_note = {
            'client_id': client_id,
            'display_name': client_dict.get('display_name') or '',
            'first_seen': client_dict['first_seen'],
            'last_seen': client_dict['last_seen'],
            'profile_summary': client_dict.get('profile_summary', ''),
            'wheel_position': client_dict.get('wheel_position', ''),
        }

        safe_name, profile_content, stats = process_client(
            db, user_for_note, client_id, 'client_id', 'website'
        )
        action = write_client_files(safe_name, profile_content, stats)

        if action == 'created':
            created += 1
        else:
            updated += 1
        print(f"  {action.capitalize()}: {safe_name}.md ({stats['total_messages']} messages)")

    db.close()
    return created, updated, len(clients)


