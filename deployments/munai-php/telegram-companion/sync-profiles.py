def extract_highlights(messages: list) -> dict:
    """Scan all messages for Harmonism keyword matches.

    Returns a dict:
        {
            'by_domain': { 'Doctrine': [(timestamp, role, matched_term, context_line), ...], ... },
            'total_matches': int,
            'unique_terms': set of matched terms,
        }
    """
    by_domain = {domain: [] for domain in HARMONISM_KEYWORDS}
    unique_terms = set()

    # Build reverse lookup: lowercase term -> (domain, canonical_term)
    term_lookup = {}
    for domain, terms in HARMONISM_KEYWORDS.items():
        for term in terms:
            term_lookup[term.lower()] = (domain, term)

    for role, content, ts in messages:
        if not content:
            continue
        matches = _KEYWORD_PATTERN.findall(content)
        if not matches:
            continue

        # Deduplicate matches within this single message
        seen_in_msg = set()
        for match in matches:
            match_lower = match.lower()
            if match_lower in seen_in_msg:
                continue
            seen_in_msg.add(match_lower)

            if match_lower in term_lookup:
                domain, canonical = term_lookup[match_lower]
                unique_terms.add(canonical)

                # Extract a context line — the sentence or ~120 chars around the match
                context = _extract_context(content, match)

                by_domain[domain].append((ts, role, canonical, context))

    # Remove empty domains
    by_domain = {d: hits for d, hits in by_domain.items() if hits}

    return {
        'by_domain': by_domain,
        'total_matches': sum(len(v) for v in by_domain.values()),
        'unique_terms': unique_terms,
    }


def _extract_context(text: str, match: str) -> str:
    """Extract a ~150-char context window around the first occurrence of match in text."""
    idx = text.lower().find(match.lower())
    if idx == -1:
        return text[:150] + ('...' if len(text) > 150 else '')

    start = max(0, idx - 60)
    end = min(len(text), idx + len(match) + 60)

    fragment = text[start:end].strip()
    if start > 0:
        fragment = '...' + fragment
    if end < len(text):
        fragment = fragment + '...'

    return fragment


def format_highlights(highlights: dict) -> str:
    """Format highlights dict into a readable vault section (with context quotes).
    DEPRECATED — use format_highlights_domains_only for privacy-respecting output."""
    if not highlights['by_domain']:
        return '*No Harmonism-specific terms detected in conversation yet.*'

    sections = []
    sections.append(
        f"Across {highlights['total_matches']} keyword occurrences, "
        f"{len(highlights['unique_terms'])} distinct Harmonism terms appeared in dialogue."
    )

    for domain, hits in sorted(highlights['by_domain'].items(), key=lambda x: -len(x[1])):
        domain_terms = sorted(set(h[2] for h in hits))
        sections.append(f"**{domain}** ({len(hits)} mentions): {', '.join(domain_terms)}")

        recent_hits = hits[-5:]
        for ts, role, term, context in recent_hits:
            time_str = format_timestamp_full(ts)
            speaker = "Client" if role == "user" else "Companion"
            clean_ctx = context.replace('\n', ' ').replace('\r', '')
            sections.append(f"> *{speaker}, {time_str}* — {clean_ctx}")

    return '\n\n'.join(sections)


def format_highlights_domains_only(highlights: dict) -> str:
    """Format keyword domain coverage without quoting message content (privacy-respecting).
    Shows which Harmonism domains the practitioner has engaged with and term frequency,
    but never includes actual conversation text."""
    if not highlights['by_domain']:
        return '*No Harmonism-specific terms detected in conversation yet.*'

    sections = []
    sections.append(
        f"{len(highlights['unique_terms'])} distinct Harmonism terms across "
        f"{highlights['total_matches']} occurrences in dialogue."
    )

    for domain, hits in sorted(highlights['by_domain'].items(), key=lambda x: -len(x[1])):
        domain_terms = sorted(set(h[2] for h in hits))
        sections.append(f"**{domain}** ({len(hits)} mentions): {', '.join(domain_terms)}")

    return '\n\n'.join(sections)


