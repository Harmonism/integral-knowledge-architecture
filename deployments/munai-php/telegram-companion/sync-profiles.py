def sync_profiles(skip_download: bool = False):
    """Main sync pipeline — processes both Telegram and website databases."""

    # Step 1: Download databases
    if not skip_download:
        downloaded = download_all_databases()
        if not downloaded:
            print("Failed to download any database. Use --local to sync from local copies.")
            sys.exit(1)
        print(f"  Downloaded {len(downloaded)} database(s): {', '.join(downloaded.keys())}")

